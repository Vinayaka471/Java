import java.util.Scanner;
public class Java_5 {
    public static void main(String[] args) {
        int i;
        for (i = 0; i <= 10; i++) {
            if (i == 5) {
                System.out.println("End of the loop");
                break;
            }

            System.out.println(i);
        }
    }
}


//Break in java: It is used to terminate the loop it is enclosed inside.